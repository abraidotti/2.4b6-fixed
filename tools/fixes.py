"""Write FIXES.md from the commits since stock-2.4b6: every change to the game, grouped by kind.

Usage, from the repo root:  python tools/fixes.py          (writes FIXES.md)
                            python tools/fixes.py --check  (fails if FIXES.md is out of date)

A commit that changes the game carries trailers, in one block at the end of its message:
    Kind: build | crash | behaviour | message
    Fixes: #N   (or Refs: #N, for a build change made under an issue it doesn't close)
A commit with no Kind trailer (tools, tests, docs) isn't listed. Stdlib only.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "FIXES.md"
REPO = "https://github.com/abraidotti/2.4b6-fixed"
KINDS = [
    ("crash", "Crashes and hangs"),
    ("behaviour", "Wrong behaviour"),
    ("message", "Messages"),
    ("build", "Building on current compilers"),
]


def commits():
    fmt = "%H%x1f%s%x1f%(trailers:key=Kind,valueonly,separator=%x2C)%x1f" \
          "%(trailers:key=Fixes,valueonly,separator=%x2C)%x1f%(trailers:key=Refs,valueonly,separator=%x2C)%x1e"
    out = subprocess.run(["git", "-C", str(ROOT), "log", "--reverse", "--no-merges", f"--format={fmt}",
                          "stock-2.4b6..HEAD"], capture_output=True, text=True, check=True).stdout
    for rec in out.split("\x1e"):
        rec = rec.strip("\n")
        if rec:
            sha, subject, kind, fixes, refs = (f.strip() for f in rec.split("\x1f"))
            yield sha, subject, kind, fixes, refs


def link(issues):
    return ", ".join(f"[{i.strip()}]({REPO}/issues/{i.strip().lstrip('#')})" for i in issues.split(",") if i.strip())


def render():
    rows = {k: [] for k, _ in KINDS}
    for sha, subject, kind, fixes, refs in commits():
        if not kind:
            continue
        if kind not in rows:
            sys.exit(f"{sha[:7]} {subject}: Kind {kind!r} isn't one of {', '.join(rows)}")
        rows[kind].append((sha, subject, link(fixes) or link(refs)))
    total = sum(len(v) for v in rows.values())
    lines = [
        "# Fixes",
        "",
        "Generated by `python tools/fixes.py` from the commits' `Kind:` trailers. Don't edit this file by hand.",
        "",
        f"Every change to the game since [`stock-2.4b6`]({REPO}/tree/stock-2.4b6), Russ Taylor's release, one commit",
        f"each: **{total} so far**. `git diff stock-2.4b6 main` shows them all at once, and",
        "[triage/README.md](triage/README.md) lists the bugs still to fix.",
    ]
    for kind, title in KINDS:
        lines += ["", f"## {title} ({len(rows[kind])})", ""]
        if not rows[kind]:
            lines.append("None yet.")
            continue
        lines += ["| Commit | Change | Issue |", "|---|---|---|"]
        for sha, subject, issue in rows[kind]:
            lines.append(f"| [`{sha[:7]}`]({REPO}/commit/{sha}) | {subject.replace('|', chr(92) + '|')} | {issue} |")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit("FIXES.md is out of date: run python tools/fixes.py")
        print("FIXES.md is up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote FIXES.md")


main()
