"""Write triage/README.md from triage/bugs.csv: which of the bugs found in QuickMUD-Python are in stock ROM 2.4b6.

Usage, from the repo root:  python tools/triage.py          (writes triage/README.md)
                            python tools/triage.py --check  (fails if triage/README.md is out of date)

Each row of bugs.csv is one bug from an issue in abraidotti/QuickMUD-Python, with a verdict:
  stock      the bug is in stock ROM 2.4b6's code, as QuickMUD has it
  quickmud   QuickMUD only: an add-on, or code QuickMUD changed (stock is fine, or has no such code)
  different  stock has the code but differs, so the bug can't happen the same way
Every function a "stock" or "different" row names must be in stock's src/ (read from the files at the
stock-2.4b6 tag, which are the files in src/ until a fix changes them), or this fails. Stdlib only.
"""
import csv
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "triage" / "bugs.csv"
OUT = ROOT / "triage" / "README.md"
TAG = "stock-2.4b6"
REPO = "https://github.com/abraidotti/2.4b6-fixed"
ISSUES = "https://github.com/abraidotti/QuickMUD-Python/issues"
VERDICTS = {
    "stock": "In stock ROM 2.4b6",
    "different": "Stock, but different",
    "quickmud": "QuickMUD only",
}
DEF = re.compile(r"^[A-Za-z_][\w \t\*]*?\b([A-Za-z_]\w*)\s*\(")
SKIP = {"if", "while", "for", "switch", "return", "sizeof"}


def stock_files():
    """(name, lines) for each src/*.c file at the stock tag."""
    names = subprocess.run(["git", "-C", str(ROOT), "ls-tree", "--name-only", TAG, "src/"],
                           capture_output=True, text=True, check=True).stdout.split()
    for name in names:
        if name.endswith(".c"):
            text = subprocess.run(["git", "-C", str(ROOT), "show", f"{TAG}:{name}"],
                                  capture_output=True, check=True).stdout.decode("latin-1")
            yield name, text.splitlines()


def functions():
    """{function: (path, line)} for ROM-style definitions: a column-0 line with '(' and no ';', then a '{' line."""
    found = {}
    for path, lines in stock_files():
        i, n = 0, len(lines)
        while i < n:
            m = DEF.match(lines[i])
            if m and m.group(1) not in SKIP and not lines[i].rstrip().endswith(";"):
                j = i + 1
                while j < n and j < i + 8 and not lines[j].startswith("{") and not lines[j].rstrip().endswith(";"):
                    j += 1
                if j < n and lines[j].startswith("{"):
                    found.setdefault(m.group(1), (path, i + 1))
            i += 1
    return found


def where(row, index):
    names = row["function"].split()
    if row["verdict"] == "quickmud":
        return ", ".join(f"`{n}`" for n in names) or "the command table"
    if not names:
        return "the command table (`src/interp.c`)"
    out = []
    for n in names:
        path, line = index[n]
        out.append(f"[`{n}`]({REPO}/blob/{TAG}/{path}#L{line})")
    return ", ".join(out)


def render(rows, index):
    count = Counter(r["verdict"] for r in rows)
    issues = sorted({int(r["issue"]) for r in rows})
    stock_issues = sorted({int(r["issue"]) for r in rows if r["verdict"] == "stock"})
    lines = [
        "# Which QuickMUD-Python bugs are in stock ROM 2.4b6",
        "",
        "Generated by `python tools/triage.py` from [bugs.csv](bugs.csv). Don't edit this file by hand.",
        "",
        f"Porting QuickMUD to Python ([abraidotti/QuickMUD-Python]({ISSUES[:-7]})) turned up bugs in its C. QuickMUD is a",
        "derivative of ROM 2.4b6, with add-ons (OLC, mob programs, boards, colour, copyover) and changes of its own, so",
        f"each bug was checked against the stock code at the [`{TAG}`]({REPO}/tree/{TAG}) tag: is the same function",
        "there, with the same faulty lines?",
        "",
        f"**{len(rows)} bugs from {len(issues)} issues:**",
        "",
        f"- **{count['stock']} in stock ROM 2.4b6**, from {len(stock_issues)} issues. These are what this repo fixes.",
        f"- **{count['different']} stock, but different:** stock has the code, but the bug can't happen the same way.",
        f"- **{count['quickmud']} QuickMUD only:** an add-on, or code QuickMUD changed. Not fixed here.",
        "",
        "An issue with several bugs has a row for each, numbered as in the issue. A row with no number is the whole",
        "issue. Links to stock code point at the function's first line at the tag.",
        "",
        "**Not examined:** stock code that QuickMUD replaced or removed (for example `note.c`, which QuickMUD's",
        "boards replaced) was never read during the port, so its bugs, if any, aren't in this table. That code is",
        "unexamined, not fixed.",
    ]
    for verdict, title in VERDICTS.items():
        group = [r for r in rows if r["verdict"] == verdict]
        lines += ["", f"## {title} ({len(group)})", "", "| Issue | Bug | Where | Note |", "|---|---|---|---|"]
        for r in group:
            item = f" ({r['item']})" if r["item"] else ""
            note = r["note"].replace("|", "\\|")
            summary = r["summary"].replace("|", "\\|")
            lines.append(f"| [#{r['issue']}]({ISSUES}/{r['issue']}){item} | {summary} | {where(r, index)} | {note} |")
    return "\n".join(lines) + "\n"


def main():
    with open(CSV, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    index = functions()
    bad = [f"#{r['issue']} ({r['item'] or '-'}): verdict {r['verdict']!r}" for r in rows if r["verdict"] not in VERDICTS]
    bad += [f"#{r['issue']} ({r['item'] or '-'}): {n} isn't in stock's src/"
            for r in rows if r["verdict"] != "quickmud" for n in r["function"].split() if n not in index]
    if bad:
        sys.exit("bugs.csv:\n  " + "\n  ".join(bad))
    text = render(rows, index)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit("triage/README.md is out of date: run python tools/triage.py")
        print("triage/README.md is up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} bugs")


main()
